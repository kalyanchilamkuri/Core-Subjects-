// - fly()                                        penguin extends bird
// Penguin extends Bird


// 4) ISP --> interface segregation principle (ISP)
// dont force someone to do things they dont need
// def: no client should be forced to depend on the methods it does not use 
// big interfaces causes dummy methods , empty implementations 

