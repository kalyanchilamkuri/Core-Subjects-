// SOLID PRINCIPLES 

// solid is a set of five object-oriented design principles that help developers create sustainable , maintanable , flexible and scalable software by reducing tight coupling and increasing the clarity of responsibility 

// 1) S ------------->SRP (single responsibility principle)
// one person -> one job 
// if one process does everything --> mess
// def: -> a class should have only one reason to change , meaning it should have only one responsibility
// when one class does logging , validation and everything => a small change breaks everything 

// 2) O ------------->OCP (open / closed principle)
// you should be able to add new features without breaking the old toys 
// software entities should be open for extension but not for modification 


// 3) Liskov substitution principle 
// if something looks like a bird then it should behave like a bird 
// def:objects of superclass should be replaceable with objects of its subclasses without breaking the correctness of the program.
