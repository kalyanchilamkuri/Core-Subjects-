
// System Design is the process of defining the architecture, components, interfaces, and data flow of a software system so that it meets functional requirements (what it should do) and non-functional requirements (scale, performance, reliability, security).

// An Operating System is system software that manages hardware resources, provides services to application programs, and ensures efficient, fair, and secure execution of programs.

// a program is an executable file 

// a process is a program in execution 

// a thread is the smallest unit of execution with in a process , sharing memory and resources with other threads of the same process

// Multitasking is the ability of an OS to execute multiple processes concurrently by rapidly switching the CPU among them.

// Multithreading is the execution of multiple threads within a single process to improve performance and responsiveness.

// Context switching is the process of saving the state of a running process or thread and restoring the state of another so execution can resume correctly.

// Too many threads/processes =
// ❌ more context switches = ❌ slower system

// The kernel is the core component of the OS that and directly manages CPU, memory, devices, and system calls.

// User space is the memory area where application programs execute with restricted access to system resources.

// A system call is an interface through which a user program requests services from the kernel.

//Memory Management is the function of an operating system that controls the allocation, deallocation, protection, and mapping of main memory so that multiple processes can execute efficiently and safely.

// memory management directly impacts the performance scalability and reliability

// A logical address is an address generated by the CPU during program execution that does not directly correspond to a physical memory location.

// A physical address is the actual location in RAM accessed by memory hardware.

// The Memory Management Unit (MMU) is a hardware component that performs runtime translation of logical addresses into physical addresses.

// MMU enables virtual memory , protections , paging 

// Swapping is the process of temporarily moving a process from main memory to secondary storage to free up memory for other processes. swapping helps to run more processes than RAM allows and avoids system crashes 

// FCFS schedules processes in the order they arrive in the ready queue.
// convoy effect occurs in fcfs because one slow process blocks many fast processes.

// sjf => minimum average waiting time 

// priority scheduling => Priority scheduling assigns CPU to processes based on priority values.

// Round Robin is a preemptive scheduling algorithm where each process is given a fixed time quantum in cyclic order.
// king , best , no starvation , best for time-sharing systems 

// Concurrency is the ability of a system to handle multiple execution paths that overlap in time.

// A race condition occurs when multiple threads access shared data concurrently and the final outcome depends on execution order.

// Synchronization ensures controlled access to shared resources so that concurrent execution does not lead to incorrect results.

// A deadlock is a situation where two or more processes are permanently blocked, each waiting for resources held by others

// Virtual Memory is a memory management technique that gives processes the illusion of a large, contiguous memory space by storing only required portions of a process in main memory while the rest resides on secondary storage.

// with virtual memory , programs can be larger than the RAM , better multiprogramming , isolation and protection 

// Concept	Meaning
// Page	Fixed-size block of logical memory
// Frame	Fixed-size block of physical memory
// Page Table	Mapping from page → frame

// Paging => instead of one big book , tear the book into equal pages and then put some pages on the table and remaining on the shelf . os moves pages not the books 

// paging => no external fragmentation , easy memory allocation , efficient swapping 

// Page Table => page table is a map => It tells which page is currently sitting on that desk 

// page table is a data structure maintained by the os that maps the virtual page numbers to physical frame numbers

// page table stores frame number , valid or invalid bit , protection bits , dirty bit , reference bit

// TLB -> translation lookaside buffer --> a transition lookaside buffer (TLB) is a small , fast cache that stores recent virtual-to-physical address translations to reduce memory access time 

// with TLB --> fast address translation and high performance 

// Page Fault --> a page fault occurs when a process accesses a page that is not currently present in the memory 

// page fault handling steps --> update page table 

// Page replacement  ==> when the table is full , to bring a new page we must remove the old page 

// page replacement is the process of selecting a page in memory to be swapped out when a new page needs to be loaded and no free frames are available

// goal is to minimize the pagefaults , maximize the performance 

// PAGE REPLACEMENT ALGORITHMS 

// FIFO --> oldest page goes out --> fifo replaces the page that has been in the memory for long time 

// problem is with FIFO is beladly anomoly

// LRU -> least recently used -> remove page that has not been accessed for the longest time 
// very good performance , approximates the optimal 

// OPTIMAL (Theoritical)
// remove page that wont be used in the future 
// optimal replaces the page that will not be used for the longest time in the future

// Trashing -> (system killer) -> you keep running => table->shelf->tabale->shelf

// Trashing occurs when a system spends more time handling page faults than executing the actual instructions

// causes for the trashing => too many processes , too little memory , poor page replacement 













